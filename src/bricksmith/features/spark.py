def _run_current(sign: str) -> str:
    return (
        "aggregate(reverse({steps}), named_struct('on', true, 'c', 0), (st, d) -> "
        f"IF(st.on AND coalesce(d {sign} 0, false), named_struct('on', true, 'c', st.c + 1), "
        "named_struct('on', false, 'c', st.c))).c"
    )


def _run_max(sign: str) -> str:
    return (
        "aggregate({steps}, named_struct('c', 0, 'b', 0), (st, d) -> "
        f"IF(coalesce(d {sign} 0, false), named_struct('c', st.c + 1, 'b', greatest(st.b, st.c + 1)), "
        "named_struct('c', 0, 'b', st.b))).b"
    )


