"""The native Spark engine: Spark SQL expressions generated from the spec, no Python UDF.

One window per spec (``partitionBy(keys).orderBy(period).rangeBetween(-(W - 1), 0)``, W the largest window)
collects each row's history; a map from lag to history row rebuilds one positional array per column, so a
missing closing is a null at its lag. Every aggregate is a generated expression over that array (higher-order
``aggregate``/``filter``/``transform``, ``array_sort``, two-pass moments and OLS), following the catalog
definitions exactly. Divisions use ``try_divide`` and lookups ``try_element_at``, so ANSI mode never raises on
a short or empty window. :func:`sql_plan` is pure Python and returns the staged expressions; pyspark loads only
in :func:`compute_spark`.
"""

