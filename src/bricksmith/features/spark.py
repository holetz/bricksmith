def percentile_sql(q: int) -> str:
    """Return the linear-interpolation percentile template (the numpy ``linear`` method)."""
    position = f"({q / 100!r}D * ({{n}} - 1))"
    low = f"CAST(floor({position}) AS INT)"
    lo = f"try_element_at({{sorted}}, {low} + 1)"
    hi = f"try_element_at({{sorted}}, least({low} + 2, {{n}}))"
    return f"{lo} + ({position} - floor({position})) * ({hi} - {lo})"


def quote(name: str) -> str:
    """Quote an identifier for Spark SQL."""
    return "`" + name.replace("`", "``") + "`"


def literal(text: str) -> str:
    """Quote a string literal for Spark SQL."""
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def array_column(column: str) -> str:
    """Return the name of the positional array column of a source column."""
    return f"__f_a_{column}"


@dataclass(frozen=True)
class Plan:
    """Staged Spark SQL.

    ``stages`` are ``(alias, expression)`` pairs over the previous stages' columns; ``outputs`` are the windowed
    and category outputs; ``combined`` are the ratios and differences, applied in order after them; ``sources``
    are the source columns the combined outputs read at the current closing.
    """

    stages: tuple[tuple[tuple[str, str], ...], ...]
    outputs: tuple[tuple[str, str], ...]
    combined: tuple[tuple[str, str], ...] = ()
    sources: tuple[str, ...] = ()


class _Builder:
    """Resolve intermediates on demand and assign each to the stage after its dependencies."""

    def __init__(self) -> None:
        self.level: dict[str, int] = {}
        self.sql: dict[str, str] = {}

    def add(self, alias: str, sql: str, deps: Iterable[str]) -> str:
        if alias not in self.sql:
            self.sql[alias] = sql
            self.level[alias] = 1 + max((self.level.get(d, 0) for d in deps), default=0)
        return alias

    def stages(self) -> tuple[tuple[tuple[str, str], ...], ...]:
        depth = max(self.level.values(), default=0)
        return tuple(
            tuple((a, self.sql[a]) for a in self.sql if self.level[a] == level) for level in range(1, depth + 1)
        )


def _steps_sql(w: int) -> str:
    if w < 2:  # noqa: PLR2004 - a single position has no step
        return "CAST(array() AS ARRAY<DOUBLE>)"
    return "transform(sequence(1, {w} - 1), i -> element_at({chrono}, i + 1) - element_at({chrono}, i))"


def _fields(template: str) -> list[str]:
    import string  # noqa: PLC0415 - only the planner parses templates

    return [f for _, f, _, _ in string.Formatter().parse(template) if f]


class _Window:
    """The intermediates of one column and window, resolved into the builder by name."""

    def __init__(self, builder: _Builder, column: str, w: int) -> None:
        self.builder = builder
        self.column = column
        self.w = w
        self.values: dict[str, str] = {"a": array_column(column), "w": str(w)}
        bounds = tercile_bounds(w)
        for j, (start, stop) in enumerate(bounds):
            self.values[f"tercile{j}"] = f"slice({{chrono}}, {start + 1}, {stop - start})"

    def render(self, template: str) -> tuple[str, set[str]]:
        deps: set[str] = set()
        mapping: dict[str, str] = {}
        for field in _fields(template):
            if field in mapping:
                continue
            if field in ("a", "w"):
                mapping[field] = self.values[field]
                if field == "a":
                    deps.add(self.values["a"])
            elif field.startswith("tercile"):
                inner, inner_deps = self.render(self.values[field])
                mapping[field] = inner
                deps |= inner_deps
            elif field == "steps_sql":
                inner, inner_deps = self.render(_steps_sql(self.w))
                mapping[field] = inner
                deps |= inner_deps
            else:
                alias = self.resolve(field)
                mapping[field] = quote(alias)
                deps.add(alias)
        return template.format(**mapping), deps

    def resolve(self, name: str) -> str:
        alias = f"__f_{name}_{self.column}_{self.w}"
        if alias not in self.builder.sql:
            sql, deps = self.render(INTERMEDIATES[name])
            self.builder.add(alias, sql, deps)
        return alias


def _aggregate_sql(window: _Window, name: str) -> tuple[str, set[str]]:
    entry = aggregate(name)
    cast = "BIGINT" if entry.kind == INTEGER else "DOUBLE"
    if window.w < entry.min_window:
        return f"CAST(NULL AS {cast})", set()
    q = percentile_of(name)
    template = percentile_sql(q) if q is not None else AGGREGATES.get(name)
    if template is None:
        msg = f"the native Spark engine cannot compute {name!r}; use the arrow engine"
        raise UnsupportedAggregateError(msg)
    sql, deps = window.render(template)
    if entry.min_points:
        n, n_deps = window.render("{n}")
        sql = f"IF({n} < {entry.min_points}, NULL, {sql})"
        deps |= n_deps
    return f"CAST({sql} AS {cast})", deps


def sql_plan(spec: FeatureSpec, outputs: Iterable[str] | None = None) -> Plan:
    """Return the staged expressions of ``spec``.

    ``outputs`` restricts the plan to those windowed and category outputs and leaves the ratios and differences
    out; by default the plan computes every output.
    """
    wanted = set(outputs) if outputs is not None else {o.name for o in spec.outputs}
    produced = {o.name for o in spec.outputs}
    sources: list[str] = []
    combined: list[tuple[str, str]] = []
    builder = _Builder()
    w_max = spec.max_window
    for column in (*spec.value_columns, *spec.categorical_columns):
        kind = "STRING" if column in spec.categorical_columns else "DOUBLE"
        sql = (
            f"transform(sequence(0, {w_max - 1}), k -> CAST(try_element_at({quote(BY_LAG)}, k).{quote(column)} "
            f"AS {kind}))"
        )
        builder.add(array_column(column), sql, ())
    windows: dict[tuple[str, int], _Window] = {}
    final: list[tuple[str, str]] = []
    for output in spec.outputs:
        if output.name not in wanted:
            continue
        if output.kind == CATEGORY:
            sliced = f"slice({quote(array_column(output.column))}, 1, {output.window})"
            final.append((output.name, f"CAST(size(filter({sliced}, x -> x = {literal(output.category)})) AS BIGINT)"))
        elif output.kind in (RATIO, DIFFERENCE):
            if outputs is not None:
                continue
            for operand in (output.left, output.right):
                if operand not in produced and operand not in sources:
                    sources.append(operand)
            left, right = (_operand(produced, o) for o in (output.left, output.right))
            sql = f"try_divide({left}, {right})" if output.kind == RATIO else f"{left} - {right}"
            combined.append((output.name, f"CAST({sql} AS DOUBLE)"))
        else:
            key = (output.column, output.window)
            window = windows.setdefault(key, _Window(builder, *key))
            sql, _ = _aggregate_sql(window, output.aggregate)
            final.append((output.name, sql))
    return Plan(builder.stages(), tuple(final), tuple(combined), tuple(sources))


def _operand(produced: set[str], name: str) -> str:
    return quote(name) if name in produced else f"CAST({quote(source_column(name))} AS DOUBLE)"


def source_column(name: str) -> str:
    """Return the alias a source column read by a ratio or difference is carried under."""
    return f"__f_src_{name}"


def _f() -> Any:  # noqa: ANN401 - the pyspark functions module
    from pyspark.sql import functions as f  # noqa: PLC0415 - heavy integration, loaded where used  # pyright: ignore[reportMissingImports]

    return f


def with_history(df: DataFrame, spec: FeatureSpec) -> DataFrame:
    """Add the period index, the window history and the lag map every positional array is read from."""
    f = _f()
    from pyspark.sql import Window  # noqa: PLC0415 - heavy integration  # pyright: ignore[reportMissingImports]

    closing = f"CAST({quote(spec.closing)} AS DATE)"
    period = f.expr(PERIOD_SQL[spec.period].format(c=closing))
    columns = (*spec.value_columns, *spec.categorical_columns)
    window = Window.partitionBy(*spec.keys).orderBy(PERIOD).rangeBetween(-(spec.max_window - 1), 0)
    history = f.collect_list(f.struct(f.col(PERIOD).alias("p"), *(f.col(c) for c in columns))).over(window)
    by_lag = f"map_from_entries(transform({quote(HISTORY)}, h -> struct({quote(PERIOD)} - h.p, h)))"
    return (
        df.withColumn(spec.closing, f.expr(closing))
        .withColumn(PERIOD, period)
        .withColumn(HISTORY, history)
        .withColumn(BY_LAG, f.expr(by_lag))
    )


def apply_plan(df: DataFrame, spec: FeatureSpec, plan: Plan) -> DataFrame:
    """Run the staged expressions of ``plan`` on a frame that went through :func:`with_history`."""
    f = _f()
    for stage in plan.stages:
        df = df.withColumns({alias: f.expr(sql) for alias, sql in stage})
    keep = [f.col(quote(k)) for k in (*spec.keys, spec.closing)]
    carried = [f.col(quote(c)).alias(source_column(c)) for c in plan.sources]
    df = df.select(*keep, *carried, *(f.expr(sql).alias(name) for name, sql in plan.outputs))
    for name, sql in plan.combined:
        df = df.withColumn(name, f.expr(sql))
    return df.select(*keep, *(f.col(quote(n)) for n, _ in (*plan.outputs, *plan.combined)))


def refuse_future(df: DataFrame, spec: FeatureSpec, as_of: date | str | None) -> date | None:
    """Refuse rows after ``as_of`` (one remote probe) and return the cutoff date."""
    if as_of is None:
        return None
    cutoff = to_date(as_of)
    f = _f()
    late = df.where(f.expr(f"CAST({quote(spec.closing)} AS DATE)") > f.lit(cutoff)).select(spec.closing).limit(3)
    check_point_in_time([to_date(r[0]) for r in late.collect()], cutoff)
    return cutoff


def compute_spark(
    df: DataFrame, spec: FeatureSpec, as_of: date | str | None = None, outputs: Iterable[str] | None = None
) -> DataFrame:
    """Return one row per entity and closing of ``df`` (or only ``as_of``) with the outputs of ``spec``.

    Duplicate entity rows within one period make Spark refuse the lag map (duplicate map key).
    """
    cutoff = refuse_future(df, spec, as_of)
    result = apply_plan(with_history(df, spec), spec, sql_plan(spec, outputs))
    if cutoff is not None:
        result = result.where(_f().col(quote(spec.closing)) == _f().lit(cutoff))
    return result
