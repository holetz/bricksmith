"""Model evaluation and technical documentation on the selected workspace.

The Spark evaluation equals the row engine; the document is logged to a real tracking run and regenerated byte for
byte from the persisted artifacts. The free tier cannot register a model version (its artifact listing is empty, spec
88), so the registered-version tag is proven by the unit tests over a fake store, not here.
"""
# ruff: noqa: PT018 - dense assertions on run outcomes

from __future__ import annotations

import math
from pathlib import Path
from typing import TYPE_CHECKING, Any

from bricksmith.mlops.documentation import (
    DOCUMENT_HTML,
    DOCUMENT_MARKDOWN,
    collect_run,
    development_files,
    model_specification,
    publish_document,
    render_document,
)
from bricksmith.mlops.documentation.artifacts import EVALUATION, NARRATIVE, SELECTION, SPECIFICATION, plain
from bricksmith.mlops.evaluation import evaluate
from bricksmith.mlops.selection import select_features
from bricksmith.mlops.stages import parse_development
from bricksmith.mlops.stages.rows import composition
from bricksmith.mlops.store import ModelStore

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence

    from bricksmith.clients import Clients

DDL = (
    "account_id BIGINT, closing_date STRING, sample STRING, status STRING, score DOUBLE, bad INT, grade STRING, "
    "income DOUBLE, tenure DOUBLE"
)
NAMES = [c.split()[0] for c in DDL.split(", ")]
CLOSINGS = {"train": ("2024-01-31", "2024-02-29"), "oot": ("2024-05-31",), "ttd": ("2024-07-31",)}
DEVELOPMENT: dict[str, Any] = {
    "model": "attrition",
    "entity_keys": ["account_id"],
    "as_of": "2024-12-31",
    "samples": {
        "train": {"role": "train", "start": "2024-01-31", "end": "2024-02-29"},
        "oot": {"role": "out_of_time", "start": "2024-05-31", "end": "2024-05-31"},
        "ttd": {"role": "through_the_door", "start": "2024-07-31", "end": "2024-07-31"},
    },
    "label": {"name": "bad", "horizon": 3, "definition": "the account closes within the next three closings"},
    "exclusions": [{"name": "closed", "where": {"column": "status", "op": "eq", "value": "closed"}}],
    "bands": [{"name": "A", "upper": 0.3}, {"name": "B", "upper": 0.6}, {"name": "C"}],
}
EVALUATION_CONFIG: dict[str, Any] = {
    "name": "attrition",
    "score": "score",
    "label": "bad",
    "grade": "grade",
    "features": ["income", "tenure"],
}
NARRATIVE_TEXT = {
    "purpose": "Rank active accounts by the likelihood of leaving.",
    "intended_use": "Retention campaigns only.",
    "population": "Active accounts at each closing.",
    "target": "Closure is observed from the account ledger.",
    "limitations": "Trained on a synthetic population.",
    "inherent_risk": "Low: the score only orders a contact list.",
    "materiality": "Moderate.",
}
STAMP = "2026-11-23T00:00:00+00:00"


def population() -> list[dict[str, Any]]:
    out = []
    for sample, closings in CLOSINGS.items():
        shift = {"train": 0.0, "oot": 0.05, "ttd": 0.1}[sample]
        for closing in closings:
            for i in range(120):
                score = round(min(((i * 7) % 20) / 20 + shift, 0.99), 4)
                grade = "A" if score <= 0.3 else "B" if score <= 0.6 else "C"
                out.append({"account_id": i, "closing_date": closing, "sample": sample,
                            "status": "closed" if i % 16 == 0 else "open", "score": score,
                            "bad": int((i * 3) % 20 < score * 20), "grade": grade, "income": float(i % 9),
                            "tenure": float(i % 5 + (2 if sample == "ttd" else 0))})  # fmt: skip
    return out


def close(a: object, b: object) -> bool:
    if isinstance(a, float) and isinstance(b, float):
        return math.isclose(a, b, rel_tol=1e-9, abs_tol=1e-12)
    return a == b


def same_rows(left: Sequence[Mapping[str, Any]], right: Sequence[Mapping[str, Any]], keys: tuple[str, ...]) -> None:
    index = {tuple(r[k] for k in keys): r for r in right}
    assert len(index) == len(left) == len(right)
    for row in left:
        other = index[tuple(row[k] for k in keys)]
        assert all(close(row[k], other[k]) for k in row), (row, other)


def test_spark_evaluation_equals_the_row_engine(remote_clients: Clients) -> None:
    spark = remote_clients.spark()
    rows = population()
    frame = spark.createDataFrame([tuple(r[n] for n in NAMES) for r in rows], DDL)
    development = parse_development(DEVELOPMENT)
    pure = evaluate(rows, EVALUATION_CONFIG, development)
    remote = evaluate(frame, EVALUATION_CONFIG, development)
    assert remote.samples == pure.samples == ("train", "oot", "ttd")
    same_rows(pure.results, remote.results, ("sample", "closing", "metric", "subject"))
    same_rows(pure.distribution, remote.distribution, ("sample", "closing", "metric", "subject", "bin"))
    same_rows(pure.grades, remote.grades, ("sample", "closing", "grade"))
    assert (pure.value("ttd", "csi", "tenure") or 0.0) > (pure.value("oot", "csi", "tenure") or 0.0)


def artifacts(rows: list[dict[str, Any]], model: Any) -> dict[str, Any]:  # noqa: ANN401 - the fitted estimator
    development = parse_development(DEVELOPMENT)
    selection = select_features(
        rows,
        {
            "name": "attrition",
            "closing": "closing_date",
            "target": "bad",
            "features": ["income", "tenure"],
            "development": ["2024-01-31", "2024-02-29"],
            "out_of_time": ["2024-05-31", "2024-05-31"],
            "steps": {"redundancy": False},
        },
    ).to_dict()
    evaluation = evaluate(rows, EVALUATION_CONFIG, development).to_dict()
    spec = model_specification(model, ["income", "tenure"])
    files = {
        **development_files(development, composition(rows, development, by=("sample",))),
        NARRATIVE: NARRATIVE_TEXT,
        SPECIFICATION: plain(spec),
        **{SELECTION[k]: selection[k] for k in ("ledger", "variables", "woe")},
        **{EVALUATION[k]: evaluation[k] for k in ("results", "distribution", "grades")},
        EVALUATION["evaluation"]: {k: evaluation[k] for k in ("config", "name", "samples")},
    }
    return plain(files)


def test_document_is_logged_and_regenerated(remote_clients: Clients, test_schema: str, tmp_path: Path) -> None:
    me = remote_clients.workspace().current_user.me().user_name  # type: ignore[attr-defined]
    experiment = f"/Users/{me}/{test_schema}"
    store = ModelStore.from_clients(remote_clients)
    rows = population()
    train = [r for r in rows if r["sample"] == "train" and r["status"] == "open"]
    features = (("income", "double"), ("tenure", "double"))
    from sklearn.linear_model import LogisticRegression  # noqa: PLC0415  # pyright: ignore[reportMissingImports]

    from bricksmith.mlops.adapter import feature_frame  # noqa: PLC0415

    model = LogisticRegression(max_iter=200, random_state=0).fit(
        feature_frame(features, train), [r["bad"] for r in train]
    )
    try:
        # The run is created directly: ModelStore.log_run's upload check needs list_artifacts (spec 88).
        run = store.client.create_run(store.experiment_id(experiment), run_name="document-attrition",
                                      tags={"bricksmith_model": "attrition"})  # fmt: skip
        run_id = str(run.info.run_id)
        files = artifacts(rows, model)
        for path, data in files.items():
            store.client.log_dict(run_id, data, path)
        store.client.set_terminated(run_id, "FINISHED")

        collected = collect_run(store.client, run_id, tmp_path / "first")
        assert collected.files() == files
        published = publish_document(store.client, collected, generated_at=STAMP)
        assert (published.run_id, published.model, published.version) == (run_id, None, None)

        def logged(path: str) -> bytes:
            landing = tmp_path / "logged" / path
            landing.mkdir(parents=True)
            return Path(store.client.download_artifacts(run_id, path, str(landing))).read_bytes()

        markdown, page = logged(DOCUMENT_MARKDOWN), logged(DOCUMENT_HTML)
        assert markdown == published.document.markdown.encode()
        assert page == published.document.html.encode()
        again = render_document(collect_run(store.client, run_id), generated_at=STAMP)
        assert again.markdown.encode() == markdown and again.html.encode() == page
        assert "Not recorded." not in again.markdown.split("## Feature sources")[0]
        assert "| ttd |" in again.markdown and "### Coefficients" in again.markdown
    finally:
        store.delete_experiment(experiment)
